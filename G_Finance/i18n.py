_CURRENT_LANGUAGE = "en"


def load_settings() -> Dict[str, Any]:
    """Loads user configuration settings from settings.json."""
    if os.path.exists(SETTINGS_FILE):
        try:
            with open(SETTINGS_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            return {}
    return {}


def save_settings(settings: Dict[str, Any]) -> bool:
    """Saves user configuration settings to settings.json."""
    try:
        current = load_settings()
        current.update(settings)
        with open(SETTINGS_FILE, "w", encoding="utf-8") as f:
            json.dump(current, f, indent=2, ensure_ascii=False)
        return True
    except Exception as e:
        print(f"Error saving settings: {e}")
        return False


def init_language() -> str:
    """Initializes the active language from settings.json or defaults to 'en'."""
    global _CURRENT_LANGUAGE
    cfg = load_settings()
    saved_lang = cfg.get("language", "en")
    if saved_lang in TRANSLATIONS:
        _CURRENT_LANGUAGE = saved_lang
    else:
        _CURRENT_LANGUAGE = "en"
    return _CURRENT_LANGUAGE


def get_current_language() -> str:
    """Returns the currently active language code ('en', 'zh_TW', or 'zh_CN')."""
    return _CURRENT_LANGUAGE


def set_language(lang_code: str) -> bool:
    """Sets the active language and persists choice to settings.json."""
    global _CURRENT_LANGUAGE
    if lang_code in TRANSLATIONS:
        _CURRENT_LANGUAGE = lang_code
        save_settings({"language": lang_code})
        return True
    return False


def get_available_languages() -> List[Tuple[str, str]]:
    """Returns list of (code, display_name) tuples for supported languages."""
    return list(SUPPORTED_LANGUAGES)


def t(key: str, default: Optional[str] = None, **kwargs) -> str:
    """
    Translates a key into the active language with fallback to English,
    supporting format keyword interpolation.
    """
    lang_dict = TRANSLATIONS.get(_CURRENT_LANGUAGE, TRANSLATIONS["en"])
    text = lang_dict.get(key)
    if text is None:
        text = TRANSLATIONS["en"].get(key, default or key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


